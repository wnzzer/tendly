export function normalizeLocale(value: unknown): Locale {
  return value === "en" ? "en" : DEFAULT_LOCALE;
}

export function translate(source: string, locale: Locale, values: Interpolation = {}): string {
  const template = locale === "zh-CN" && Object.hasOwn(zhCN, source) ? zhCN[source] : source;
  return template.replace(/\{([\w]+)\}/g, (placeholder: string, key: string) => Object.hasOwn(values, key) ? String(values[key]) : placeholder);
}

type LocaleStorage = Pick<Storage, "getItem" | "setItem">;

function browserStorage(): LocaleStorage | undefined {
  try { return typeof localStorage === "undefined" ? undefined : localStorage; } catch { return undefined; }
}

/** A factory makes persistence and denied-storage behavior independently testable. */
export function createI18n(storage?: LocaleStorage, onChange?: (locale: Locale) => void) {
  let initial: Locale = DEFAULT_LOCALE;
  try { initial = normalizeLocale(storage?.getItem(LOCALE_STORAGE_KEY)); } catch { /* Private mode can deny storage. */ }
  const state = ref<Locale>(initial);
  function setLocale(value: Locale) {
    state.value = normalizeLocale(value);
    try { storage?.setItem(LOCALE_STORAGE_KEY, state.value); } catch { /* Localization still works without storage. */ }
    onChange?.(state.value);
  }
  onChange?.(initial);
  return { locale: readonly(state), setLocale, t: (source: string, values?: Interpolation) => translate(source, state.value, values) };
}

let instance: ReturnType<typeof createI18n> | undefined;
export function useI18n() {
  instance ??= createI18n(browserStorage(), locale => {
    if (typeof document !== "undefined") document.documentElement.lang = locale;
  });
  return instance;
}
